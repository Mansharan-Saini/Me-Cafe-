CREATE OR REPLACE FUNCTION get_expiry_status(p_expiry_date DATE)
RETURN VARCHAR2
IS
    v_days NUMBER;
    v_urgent NUMBER;
    v_soon NUMBER;
BEGIN
    SELECT config_value INTO v_urgent FROM app_config WHERE config_key='URGENT_DAYS';
    SELECT config_value INTO v_soon FROM app_config WHERE config_key='SOON_DAYS';
    v_days := TRUNC(p_expiry_date)-TRUNC(SYSDATE);

    IF v_days < 0 THEN RETURN 'EXPIRED';
    ELSIF v_days = 0 THEN RETURN 'TODAY';
    ELSIF v_days <= v_urgent THEN RETURN 'URGENT';
    ELSIF v_days <= v_soon THEN RETURN 'SOON';
    ELSE RETURN 'SAFE';
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE add_food_item(
    p_name VARCHAR2, p_category_id NUMBER, p_quantity NUMBER,
    p_unit VARCHAR2, p_price NUMBER, p_expiry_date DATE, p_item_id OUT NUMBER
)
IS
BEGIN
    IF TRIM(p_name) IS NULL OR p_category_id IS NULL OR p_quantity IS NULL OR p_quantity < 0
       OR TRIM(p_unit) IS NULL OR p_price IS NULL OR p_price <= 0 OR p_expiry_date IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Enter a name, category, valid quantity, unit, price, and expiry date.');
    END IF;

    INSERT INTO food_items (item_name, category_id, quantity, unit, unit_price, expiry_date)
    VALUES (TRIM(p_name), p_category_id, p_quantity, TRIM(p_unit), p_price, p_expiry_date)
    RETURNING item_id INTO p_item_id;
END;
/

CREATE OR REPLACE PROCEDURE record_food_waste(
    p_item_id NUMBER, p_quantity NUMBER, p_reason_id NUMBER,
    p_user_id NUMBER, p_remarks VARCHAR2, p_waste_id OUT NUMBER
)
IS
    v_stock NUMBER;
    v_price NUMBER;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Waste quantity must be greater than zero.');
    END IF;

    SELECT quantity, unit_price INTO v_stock, v_price
    FROM food_items WHERE item_id=p_item_id AND is_active='Y'
    FOR UPDATE;

    IF p_quantity > v_stock THEN
        RAISE_APPLICATION_ERROR(-20003, 'Waste quantity cannot exceed the available stock.');
    END IF;

    INSERT INTO food_waste_log
        (item_id, reason_id, quantity_wasted, estimated_loss, recorded_by, remarks)
    VALUES
        (p_item_id, p_reason_id, p_quantity, ROUND(p_quantity*v_price, 2), p_user_id, p_remarks)
    RETURNING waste_id INTO p_waste_id;

    UPDATE food_items SET quantity=quantity-p_quantity WHERE item_id=p_item_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Food item was not found or is inactive.');
END;
/

CREATE OR REPLACE PROCEDURE check_food_expiry
IS
BEGIN
    FOR item IN (
        SELECT item_id, expiry_date
        FROM food_items
        WHERE is_active='Y' AND quantity>0
    ) LOOP
        DECLARE
            v_status VARCHAR2(20);
        BEGIN
            v_status := get_expiry_status(item.expiry_date);
            IF v_status IN ('EXPIRED', 'TODAY', 'URGENT', 'SOON') THEN
                INSERT INTO expiry_alerts (item_id, alert_type)
                SELECT item.item_id, v_status
                FROM dual
                WHERE NOT EXISTS (
                    SELECT 1 FROM expiry_alerts a
                    WHERE a.item_id=item.item_id AND a.alert_type=v_status
                      AND a.status IN ('OPEN', 'ACKNOWLEDGED')
                );
            END IF;
        EXCEPTION
            WHEN DUP_VAL_ON_INDEX THEN
                NULL;
        END;
    END LOOP;
END;
/

