-- Mini-project setup: food inventory, expiry alerts, and actual waste.
-- Run this file once as FOOD_ADMIN. Rerunning it deletes these demo tables first.
-- Procedures do not COMMIT. Flask commits on success and rolls back on errors.

SET DEFINE OFF;

BEGIN
    FOR t IN (
        SELECT column_value AS table_name
        FROM TABLE(sys.odcivarchar2list(
            'FOOD_WASTE_LOG', 'EXPIRY_ALERTS', 'FOOD_ITEMS',
            'WASTE_REASONS', 'CATEGORIES', 'APP_CONFIG', 'USERS'
        ))
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/

CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    role_name VARCHAR2(20) DEFAULT 'STAFF' NOT NULL
        CHECK (role_name IN ('ADMIN', 'STAFF'))
);

CREATE TABLE app_config (
    config_key VARCHAR2(40) PRIMARY KEY,
    config_value NUMBER NOT NULL
);

CREATE TABLE waste_reasons (
    reason_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE food_items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR2(100) NOT NULL,
    category_id NUMBER NOT NULL REFERENCES categories(category_id),
    quantity NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (quantity >= 0),
    unit VARCHAR2(20) NOT NULL,
    unit_price NUMBER(10,2) NOT NULL CHECK (unit_price > 0),
    expiry_date DATE NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    created_at DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE expiry_alerts (
    alert_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id NUMBER NOT NULL REFERENCES food_items(item_id),
    alert_type VARCHAR2(20) NOT NULL
        CHECK (alert_type IN ('EXPIRED', 'TODAY', 'URGENT', 'SOON')),
    alert_date DATE DEFAULT SYSDATE NOT NULL,
    status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL
        CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED'))
);

CREATE UNIQUE INDEX uq_one_open_alert
ON expiry_alerts (
    CASE WHEN status IN ('OPEN', 'ACKNOWLEDGED') THEN item_id END,
    CASE WHEN status IN ('OPEN', 'ACKNOWLEDGED') THEN alert_type END
);

CREATE TABLE food_waste_log (
    waste_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id NUMBER NOT NULL REFERENCES food_items(item_id),
    reason_id NUMBER NOT NULL REFERENCES waste_reasons(reason_id),
    quantity_wasted NUMBER(10,2) NOT NULL CHECK (quantity_wasted > 0),
    estimated_loss NUMBER(12,2) NOT NULL CHECK (estimated_loss >= 0),
    waste_date DATE DEFAULT SYSDATE NOT NULL,
    recorded_by NUMBER NOT NULL REFERENCES users(user_id),
    remarks VARCHAR2(250)
);

